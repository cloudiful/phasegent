// `bun run build:plugin`: link the single-file deployment artifact from
// `assets/opencode/src/**` and `skills/phasegent/*.md`.
//
// The sources are linked, not transpiled: module bodies are concatenated in
// local-import order with the `import`/`export` syntax resolved at the text
// level, and each prompt body is inlined as a template literal. The artifact
// therefore keeps every comment, `const` and `export default` spelling the
// deployment contract guards (managed marker, v2 module shape, documented
// redirect contract, byte-exact embedded skills); Bun's bundler strips all
// comments and rewrites top-level `const`/default exports, so Bun only parses
// the linked result here. The checked-in dist is generated: edit the sources or
// the markdown and rerun this script, then let the freshness tests keep it
// honest.
//
// The text link expects each module to keep statements at the start of a line,
// imports only from `./*.js` or `*.md with { type: "text" }`, and `export`
// only as a declaration prefix or `export default`; anything else fails the
// build instead of emitting a broken artifact.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO_ROOT = fileURLToPath(new URL("../../../", import.meta.url));
export const SOURCE_ENTRY = `${REPO_ROOT}assets/opencode/src/index.js`;
export const DIST_PATH = `${REPO_ROOT}assets/opencode/phasegent-worktree.js`;

// Line 1 is the managed-file marker `phasegent plugin install` looks for; the
// header keeps the checked-in artifact identifiable as generated.
const BANNER = [
  "// phasegent:managed",
  "// @generated by `bun run build:plugin` from assets/opencode/src/**; do not edit.",
].join("\n");

const TEXT_IMPORT =
  /^import\s+([A-Za-z_$][\w$]*)\s+from\s+"([^"]+\.md)"\s+with\s*\{\s*type:\s*"text"\s*\}\s*;$/;
const MODULE_IMPORT = /^import\s+[\s\S]*?\s+from\s+"(\.[^"]*)"\s*;$/;
const EXPORTED_DECLARATION = /^export\s+(const|let|var|function|async function|class)\s/;
const DEFAULT_EXPORT = /^export\s+default\s/;

function trimBlankEdges(text) {
  return text.replace(/^\n+/, "").replace(/\n+$/, "");
}

// The inlined prompt bodies become the exact bytes the runtime hands the host,
// so only the template delimiters and `${` interpolation are escaped.
function templateLiteral(content) {
  return `\`${content.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;
}

// Reads one module and rewrites it into link-ready text: local imports are
// dropped (the requested bindings share the linked scope), markdown imports
// become template literals, `export` leaves the declarations, and `export
// default` stays for the v2 module contract.
function readModule(modulePath) {
  const lines = readFileSync(modulePath, "utf8").split("\n");
  const dependencies = [];
  const body = [];
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    if (line.startsWith("import ")) {
      let statement = line;
      while (!statement.trimEnd().endsWith(";")) {
        index += 1;
        if (index >= lines.length) {
          throw new Error(`unterminated import in ${modulePath}`);
        }
        statement += `\n${lines[index]}`;
      }
      const textImport = statement.match(TEXT_IMPORT);
      if (textImport) {
        const contentPath = resolve(dirname(modulePath), textImport[2]);
        const content = readFileSync(contentPath, "utf8");
        body.push(`const ${textImport[1]} = ${templateLiteral(content)};`);
        continue;
      }
      const moduleImport = statement.match(MODULE_IMPORT);
      if (!moduleImport) {
        throw new Error(`unsupported import in ${modulePath}: ${statement}`);
      }
      dependencies.push(resolve(dirname(modulePath), moduleImport[1]));
      continue;
    }
    if (line.startsWith("export ")) {
      if (DEFAULT_EXPORT.test(line)) {
        body.push(line);
        continue;
      }
      if (!EXPORTED_DECLARATION.test(line)) {
        throw new Error(`unsupported export in ${modulePath}: ${line}`);
      }
      body.push(line.slice("export ".length));
      continue;
    }
    body.push(line);
  }
  return { path: modulePath, dependencies, body: trimBlankEdges(body.join("\n")) };
}

// Local-import order guarantees every dependency is declared before the module
// that uses it, and the entry (with its `export default`) lands last.
function orderedModules(entryPath) {
  const seen = new Set();
  const ordered = [];
  const visit = (modulePath) => {
    if (seen.has(modulePath)) return;
    seen.add(modulePath);
    const module = readModule(modulePath);
    for (const dependency of module.dependencies) visit(dependency);
    ordered.push(module);
  };
  visit(entryPath);
  return ordered;
}

function renderModule(module) {
  const header = `// ${relative(REPO_ROOT, module.path).replaceAll("\\", "/")}`;
  return `${header}\n${module.body}`;
}

function validatePlugin(source) {
  try {
    // Bun's parser rejects syntax errors and duplicate declarations, i.e. the
    // same failures the host would hit while loading the plugin.
    new Bun.Transpiler({ loader: "js" }).transformSync(source);
  } catch (error) {
    const detail = String(error && error.message ? error.message : error);
    throw new Error(`linked plugin does not parse: ${detail}`);
  }
}

export function buildPlugin(outfile = DIST_PATH) {
  const source = `${BANNER}\n\n${orderedModules(SOURCE_ENTRY).map(renderModule).join("\n\n")}\n`;
  validatePlugin(source);
  writeFileSync(outfile, source);
  return outfile;
}

if (import.meta.main) {
  buildPlugin();
  console.log("built assets/opencode/phasegent-worktree.js from assets/opencode/src/index.js");
}
